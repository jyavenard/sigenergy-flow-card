#!/usr/bin/env python3
"""Embed the scene photos and charger overlays from images/ into sigenergy-flow-card.js.

The card positions everything in the coordinates of its first photo (1676 units wide).
Each photo is resampled into that frame (REGISTRATION holds the scale and offset
measured against it), so the layout does not depend on the size of the supplied image,
then extended with a band above and below (its edge rows stretched and blurred), where
the card places its readings, and stored as an AVIF data URI so the card is a single
self-contained file. AVIF needs iOS / iPadOS 16 or later, Safari on macOS 13 or later, or Chrome / Edge 85,
Firefox 93 or later; at the same quality it is about a third smaller than WebP.

The charger overlays are transparent images of the charger on the garage wall; each
is scaled so its charger has the height CHARGER_REFERENCE gives (in photo units),
centred on the wall position, cropped to its visible pixels and stored at twice the
card's resolution. The plugged-in overlays (charger_<time>_plugged.png, from
tools/make-plugged.py) keep their unplugged overlay's canvas and are placed with its scale.

The garage images are the photos with the car removed, already in the first photo's frame
(1676 pixels wide, row 0 at its top row). Only the garage's inside is kept, where they differ
from the photo, and cut at the pillar on its right (whose position the photo keeps); the card
draws that patch over the car to hide it. Run after changing any of the images:

    python3 tools/embed-artwork.py
"""

import base64
import io
import pathlib
import re

import numpy as np
from PIL import Image, ImageFilter

ROOT = pathlib.Path(__file__).resolve().parent.parent
CARD = ROOT / 'sigenergy-flow-card.js'
FILES = ['house_day.png', 'house_night.png']
OVERLAYS = ['charger_day.png', 'charger_night.png', 'charger_day_plugged.png', 'charger_night_plugged.png']
# Each garage image's photo, the x of the pillar's left edge on the garage's right and the boxes past it that
# are still taken from the garage image (the day car's mirror shows on the pillar).
GARAGES = {'garage_day.png': ('house_day.png', 617, [(617, 276, 626, 291)]), 'garage_night.png': ('house_night.png', 615, [])}
# The garage's inside (left, top, bottom) in the first photo's frame, and the difference from the photo that counts.
GARAGE_BOX, GARAGE_DIFF = (425, 195, 385), 20
# AVIF quality of the photos and of the charger overlays, and the encoder's speed (0 is slowest and smallest).
QUALITY, OVERLAY_QUALITY, SPEED = 50, 80, 2
WIDTH = 1676
# The photo's rows, starting EXTRA_TOP units above the first photo's top row.
EXTRA_TOP, ROWS = 44, 557
# Must match PHOTO.top + PHOTO.bleed and PHOTO.bottom + PHOTO.bleed in the card.
TOP, BOTTOM = 156, 160
# (pixels per unit, x offset, y offset in pixels) of each photo against the first photo's frame.
REGISTRATION = {'house_day.png': (1.2941, 0.1, 60.5), 'house_night.png': (1.2887, -1.1, 57.4)}
# Height of the charger (units), its centre x and its top y in the first photo's frame.
CHARGER_REFERENCE = {'charger_day.png': (76, 458.0, 245), 'charger_night.png': (77, 457.5, 245)}
EDGE_ROWS = 6
FEATHER = 12
BEGIN = '// BEGIN ARTWORK (generated by tools/embed-artwork.py)'
END = '// END ARTWORK'


def extend(photo):
    w, h = photo.size
    blur = ImageFilter.GaussianBlur(14)
    top = photo.crop((0, 0, w, EDGE_ROWS)).resize((w, TOP + FEATHER), Image.BILINEAR).filter(blur)
    bottom = photo.crop((0, h - EDGE_ROWS, w, h)).resize((w, BOTTOM + FEATHER), Image.BILINEAR).filter(blur)
    canvas = Image.new('RGB', (w, TOP + h + BOTTOM))
    canvas.paste(top, (0, 0))
    canvas.paste(bottom, (0, TOP + h - FEATHER))
    # Fade the photo in over the bands' overlapping rows so the seams are soft.
    mask = Image.new('L', (w, h), 255)
    for i in range(FEATHER):
        level = round(255 * (i + 1) / (FEATHER + 1))
        mask.paste(level, (0, i, w, i + 1))
        mask.paste(level, (0, h - 1 - i, w, h - i))
    canvas.paste(photo, (0, TOP), mask)
    return canvas


def overlay(name):
    image = Image.open(ROOT / 'images' / name).convert('RGBA')
    left, top, right, bottom = image.getchannel('A').getbbox()
    # The unplugged overlay's charger gives the scale and the position of its canvas.
    reference = name.replace('_plugged', '')
    alpha = Image.open(ROOT / 'images' / reference).getchannel('A')
    body_left, body_top, body_right, body_bottom = alpha.point(lambda v: 255 if v >= 64 else 0).getbbox()
    height, centre_x, body_top_y = CHARGER_REFERENCE[reference]
    unit = height / (body_bottom - body_top)
    crop = image.crop((left, top, right, bottom))
    crop = crop.resize((round(crop.width * unit * 2), round(crop.height * unit * 2)), Image.LANCZOS)
    x = centre_x - ((body_left + body_right) / 2 - left) * unit
    y = body_top_y - (body_top - top) * unit + EXTRA_TOP
    buffer = io.BytesIO()
    crop.save(buffer, 'AVIF', quality=OVERLAY_QUALITY, speed=SPEED)
    data = base64.b64encode(buffer.getvalue()).decode('ascii')
    return (f"    '{name}': {{ size: [{(right - left) * unit:.2f}, {(bottom - top) * unit:.2f}], at: [{x:.2f}, {y:.2f}], "
            f"href: 'data:image/avif;base64,{data}' }},")


def garage_mask(name):
    """The garage's inside as an alpha mask in the first photo's frame, and the garage image it came from."""
    house, pillar, extra = GARAGES[name]
    image = Image.open(ROOT / 'images' / name).convert('RGB')
    if image.width != WIDTH:
        raise SystemExit(f'{name}: must be {WIDTH} pixels wide, in the first photo\'s frame')
    photo = np.asarray(place(house), dtype=np.int16)[EXTRA_TOP:EXTRA_TOP + image.height]
    diff = np.abs(np.asarray(image, dtype=np.int16) - photo).max(2) > GARAGE_DIFF
    left, top, bottom = GARAGE_BOX
    mask = np.zeros(diff.shape, np.uint8)
    mask[top:bottom, left:pillar] = diff[top:bottom, left:pillar] * 255
    # Join the differing pixels into one area, drop stray specks, then soften its edge except against the pillar.
    area = Image.fromarray(mask).filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.MinFilter(11)).filter(ImageFilter.MaxFilter(11))
    mask = np.asarray(area.filter(ImageFilter.GaussianBlur(1.5))).copy()
    mask[:, pillar:] = 0
    mask[:, pillar - 2:pillar] = np.asarray(area)[:, pillar - 2:pillar]
    for x0, y0, x1, y1 in extra:
        mask[y0:y1, x0:x1] = 255
    return mask, image


def garage(name):
    mask, image = garage_mask(name)
    image.putalpha(Image.fromarray(mask))
    left, top, right, bottom = image.getbbox()
    buffer = io.BytesIO()
    image.crop((left, top, right, bottom)).save(buffer, 'AVIF', quality=OVERLAY_QUALITY, speed=SPEED)
    data = base64.b64encode(buffer.getvalue()).decode('ascii')
    return (f"    '{name}': {{ size: [{right - left}, {bottom - top}], at: [{left}, {top + EXTRA_TOP}], "
            f"href: 'data:image/avif;base64,{data}' }},")


def place(name):
    scale, dx, dy = REGISTRATION[name]
    photo = Image.open(ROOT / 'images' / name).convert('RGB')
    photo = photo.resize((round(photo.width / scale), round(photo.height / scale)), Image.LANCZOS)
    scale = Image.open(ROOT / 'images' / name).width / photo.width
    pad = 8
    padded = Image.fromarray(np.pad(np.asarray(photo), ((pad, pad), (pad, pad), (0, 0)), mode='edge'))
    shift_x, shift_y = dx / scale + pad, dy / scale - EXTRA_TOP + pad
    return padded.transform((WIDTH, ROWS), Image.AFFINE, (1, 0, shift_x, 0, 1, shift_y), Image.BICUBIC)


def entry(name):
    image = extend(place(name))
    buffer = io.BytesIO()
    image.save(buffer, 'AVIF', quality=QUALITY, speed=SPEED)
    data = base64.b64encode(buffer.getvalue()).decode('ascii')
    return f"    '{name}': {{ size: [{image.width}, {image.height}], href: 'data:image/avif;base64,{data}' }},"


def main():
    block = '\n'.join([BEGIN, 'const ARTWORK = {', *map(entry, FILES), *map(overlay, OVERLAYS), *map(garage, GARAGES), '};', END])
    source = CARD.read_text()
    pattern = re.compile(re.escape(BEGIN) + '.*?' + re.escape(END), re.S)
    if not pattern.search(source):
        raise SystemExit(f'{CARD.name}: artwork markers not found')
    CARD.write_text(pattern.sub(lambda _: block, source))
    print(f'{CARD.name}: {CARD.stat().st_size // 1024} KiB')


if __name__ == '__main__':
    main()
